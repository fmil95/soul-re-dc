#!/usr/bin/env python3
"""Generate asm/nonmatchings/<file>/<func>.s for every game function listed in config/functions.csv.

Each function is emitted for the KATANA SDK gas (binutils 2.9), which must reproduce it byte for byte:
  * instructions as `.word 0xXXXX` with the SDK objdump disassembly as a `!` comment
  * literal-pool words that hold addresses as `.long <symbol>` (functions by name, data as D_<ADDR>),
    so code can move once functions are replaced by C (Ship of Theseus)
  * every function starts with `.align 5` (GCC aligns SH functions to 32 bytes); trailing alignment padding
    is dropped and regenerated by gas (nops, inside an object) or ld (zeros, between objects)

Library entry point: generate(rom, functions_csv, listing=None, lib_names=None) -> (files, data_symbols)
"""
import csv
import os
import re
import struct

VRAM = 0x8C010000
GAME_TEXT = (0x8C05AC20, 0x8C12A9E0)
RAM_END = 0x8D000000


def read_functions(path):
    rows = []
    with open(path) as f:
        for r in csv.DictReader(l for l in f if not l.startswith("#")):
            rows.append((int(r["addr"], 16), r["file"], r["name"]))
    rows.sort()
    return rows


def parse_listing(path, base):
    """offset-addressed objdump -d output of the game text blob -> {addr: 'mnemonic operands'}"""
    out = {}
    if not path or not os.path.exists(path):
        return out
    tgt = re.compile(r"\b([0-9a-f]+) <[^>]*>")
    for line in open(path, encoding="latin1"):
        m = re.match(r"^\s*([0-9a-f]+):\t(?:[0-9a-f]{2} ){2}\s*\t(.*)$", line.rstrip("\n"))
        if m:
            text = tgt.sub(lambda t: f"0x{base + int(t.group(1), 16):08X}", m.group(2)).replace("\t", " ").strip()
            out[base + int(m.group(1), 16)] = text
    return out


def generate(rom, functions_csv, asm_root="asm/nonmatchings", listing=None, lib_names=None):
    funcs = read_functions(functions_csv)
    names = {a: n for a, _, n in funcs}
    lib_names = lib_names or {}
    comments = parse_listing(listing, GAME_TEXT[0])
    data_syms = {}
    files = []  # ordered unique file list

    def hw(a):
        return struct.unpack_from("<H", rom, a - VRAM)[0]

    def sym_for(v):
        if v in names:
            return "_" + names[v]
        if v in lib_names:
            return "_" + lib_names[v]
        if VRAM <= v < RAM_END and not (GAME_TEXT[0] <= v < GAME_TEXT[1]):
            s = f"_D_{v:08X}"
            data_syms[s] = v
            return s
        return None

    written = 0
    for i, (addr, fl, name) in enumerate(funcs):
        if not files or files[-1] != fl:
            files.append(fl)
        nxt = funcs[i + 1][0] if i + 1 < len(funcs) else GAME_TEXT[1]
        last_in_file = i + 1 == len(funcs) or funcs[i + 1][1] != fl
        pad = 0x0000 if last_in_file else 0x0009
        # Drop alignment padding, but never so much that the next 32-byte boundary comes before `nxt`
        # (a delay-slot nop right before the padding is indistinguishable from it and may go too).
        end = nxt
        while end - 2 > max(addr, nxt - 32) and hw(end - 2) == pad:
            end -= 2

        pools = set()
        for pc in range(addr, end, 2):
            op = hw(pc)
            if op & 0xF000 == 0xD000:  # mov.l @(disp,PC),Rn
                ea = ((pc + 4) & ~3) + (op & 0xFF) * 4
                if addr <= ea and ea + 4 <= end:
                    pools.add(ea)

        lines = ["\t.text", "\t.align 5", f"\t.global\t_{name}", f"_{name}:"]
        pc = addr
        while pc < end:
            if pc in pools:
                (v,) = struct.unpack_from("<I", rom, pc - VRAM)
                s = sym_for(v)
                if s:
                    lines.append(f"\t.long\t{s}\t! {pc:08X}: 0x{v:08X}")
                    pc += 4
                    continue
            op = hw(pc)
            c = comments.get(pc)
            lines.append(f"\t.word\t0x{op:04X}\t! {pc:08X}: {c}" if c else f"\t.word\t0x{op:04X}\t! {pc:08X}")
            pc += 2
        text = "\n".join(lines) + "\n"

        path = os.path.join(asm_root, fl, f"{name}.s")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if not os.path.exists(path) or open(path).read() != text:
            with open(path, "w", newline="\n") as f:
                f.write(text)
            written += 1
    return files, data_syms, written
