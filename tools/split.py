#!/usr/bin/env python3
"""Split the ROM according to config/<name>.toml.

Writes:
  build/bin/<segment>.o        ELF object wrapping the raw bytes of every `bin` segment
  build/<name>.ld              linker script placing every segment at its address
  build/<name>.objs            list of object files the link needs (one per line)

Usage: split.py config/1st_read.toml
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bin2elf  # noqa: E402

try:
    import tomllib
except ImportError:  # Python < 3.11
    sys.exit("split.py needs Python 3.11+ (tomllib)")


def main():
    cfg_path = sys.argv[1]
    with open(cfg_path, "rb") as f:
        cfg = tomllib.load(f)
    b = cfg["binary"]
    rom = open(b["rom"], "rb").read()
    if len(rom) != b["size"] or hashlib.sha1(rom).hexdigest() != b["sha1"]:
        sys.exit(f"{b['rom']}: size/sha1 mismatch - wrong or modified ROM")

    vram, end = b["vram"], b["vram"] + b["size"]
    segs = cfg["segment"]
    if segs[0]["start"] != vram:
        sys.exit("first segment must start at binary vram")
    os.makedirs("build/bin", exist_ok=True)

    ld = [
        "/* generated by tools/split.py - do not edit */",
        'OUTPUT_FORMAT("elf32-shl")',
        "OUTPUT_ARCH(sh)",
        "SECTIONS",
        "{",
    ]
    objs = []
    for i, s in enumerate(segs):
        start = s["start"]
        stop = segs[i + 1]["start"] if i + 1 < len(segs) else end
        if not (vram <= start < stop <= end):
            sys.exit(f"segment {s['name']}: bad range {start:#x}-{stop:#x}")
        kind = s["kind"]
        if kind == "bin":
            obj = f"build/bin/{s['name']}.o"
            blob = bin2elf.build(rom[start - vram:stop - vram], s.get("section", ".data"), f"__seg_{s['name']}", 4)
            if not os.path.exists(obj) or open(obj, "rb").read() != blob:
                with open(obj, "wb") as f:
                    f.write(blob)
        elif kind == "asm":
            obj = f"build/asm/{s['name']}.o"
        elif kind == "c":
            obj = f"build/src/{s['name']}.o"
        else:
            sys.exit(f"segment {s['name']}: unknown kind {kind}")
        objs.append(obj)
        sec = s.get("section", ".text")
        ld.append(f"  .seg_{s['name']} 0x{start:08X} : AT(0x{start:08X})")
        secs = [sec] + [x for x in (".text", ".rodata", ".data") if x != sec]
        ld.append("  { " + " ".join(f"{obj}({x})" for x in secs) + " }")
    ld += ["  /DISCARD/ : { *(.comment) }", "}"]
    name = b["name"].lower()
    with open(f"build/{name}.ld", "w", newline="\n") as f:
        f.write("\n".join(ld) + "\n")
    with open(f"build/{name}.objs", "w", newline="\n") as f:
        f.write("\n".join(objs) + "\n")
    print(f"split {len(segs)} segments -> build/{name}.ld")


if __name__ == "__main__":
    main()
